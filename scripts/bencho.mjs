#!/usr/bin/env node
/**
 * Bencho asset tooling (docs/SPEC.md §6.4). Block source and sounds are
 * licensed and git-ignored; only our patches + this manifest are committed.
 *
 *   node scripts/bencho.mjs check    manifest vs files on disk (exit 1 if missing)
 *   node scripts/bencho.mjs apply    .pristine/* + patches/*.patch → blocks/*
 *   node scripts/bencho.mjs diff     blocks/* vs .pristine/* → patches/*.patch
 *   node scripts/bencho.mjs sounds   assets/sounds/* → src/services/sound/registry.generated.ts
 *   node scripts/bencho.mjs setup    apply + sounds + check
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const BLOCKS = path.join(root, 'src/bencho/blocks');
const PRISTINE = path.join(BLOCKS, '.pristine');
const PATCHES = path.join(root, 'src/bencho/patches');
const SOUNDS = path.join(root, 'assets/sounds');
const REGISTRY = path.join(root, 'src/services/sound/registry.generated.ts');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'src/bencho/manifest.json'), 'utf8'));
// Each area keeps its own block list so parallel work never collides
const AREAS = path.join(root, 'src/bencho/manifests');
if (fs.existsSync(AREAS)) {
  for (const f of fs.readdirSync(AREAS).filter((f) => f.endsWith('.json'))) {
    Object.assign(manifest.blocks, JSON.parse(fs.readFileSync(path.join(AREAS, f), 'utf8')).blocks ?? {});
  }
}

const blockFiles = () => Object.values(manifest.blocks).flatMap((b) => b.files);
const soundFile = (id) =>
  fs.existsSync(SOUNDS) ? fs.readdirSync(SOUNDS).find((f) => path.parse(f).name === id) : undefined;

function check() {
  const missing = [];
  for (const f of blockFiles()) if (!fs.existsSync(path.join(BLOCKS, f))) missing.push(`block  src/bencho/blocks/${f}`);
  for (const id of manifest.sounds) if (!soundFile(id)) missing.push(`sound  assets/sounds/${id}.*`);
  if (missing.length) {
    console.error(`Bencho assets missing (${missing.length}). See docs/SPEC.md §6.4:\n  ` + missing.join('\n  '));
    process.exitCode = 1;
  } else console.log(`Bencho assets OK: ${blockFiles().length} block files, ${manifest.sounds.length} sounds.`);
}

function apply() {
  for (const f of blockFiles()) {
    const src = path.join(PRISTINE, f);
    if (!fs.existsSync(src)) { console.warn(`skip ${f}: no pristine copy`); continue; }
    const out = path.join(BLOCKS, f);
    fs.copyFileSync(src, out);
    const p = path.join(PATCHES, `${f}.patch`);
    if (fs.existsSync(p)) {
      execFileSync('patch', ['--silent', out, p], { stdio: 'inherit' });
      console.log(`patched ${f}`);
    } else console.log(`copied  ${f}`);
  }
}

function diff() {
  fs.mkdirSync(PATCHES, { recursive: true });
  for (const f of blockFiles()) {
    const a = path.join(PRISTINE, f), b = path.join(BLOCKS, f);
    if (!fs.existsSync(a) || !fs.existsSync(b)) continue;
    let out = '';
    try { execFileSync('diff', ['-u', a, b]); } catch (e) { out = e.stdout.toString(); }
    const p = path.join(PATCHES, `${f}.patch`);
    if (out) {
      out = out.replace(/^--- .*$/m, `--- a/${f}`).replace(/^\+\+\+ .*$/m, `+++ b/${f}`);
      fs.writeFileSync(p, out);
      console.log(`wrote patches/${f}.patch`);
    } else if (fs.existsSync(p)) fs.rmSync(p);
  }
}

function sounds() {
  const files = fs.existsSync(SOUNDS) ? fs.readdirSync(SOUNDS).filter((f) => /\.(mp3|wav|m4a|aac|ogg|caf)$/i.test(f)) : [];
  const lines = files.sort().map((f) => `  ${JSON.stringify(path.parse(f).name)}: require('../../../assets/sounds/${f}'),`);
  fs.writeFileSync(
    REGISTRY,
    `// Generated by scripts/bencho.mjs — do not edit. Git-ignored.\nexport const SOUND_FILES: Record<string, number> = {\n${lines.join('\n')}\n};\n`
  );
  console.log(`registry: ${files.length} sounds`);
}

const commands = { check, apply, diff, sounds, setup: () => { apply(); sounds(); check(); } };
const run = commands[process.argv[2]];
if (run) run();
else console.log('usage: node scripts/bencho.mjs check|apply|diff|sounds|setup');
